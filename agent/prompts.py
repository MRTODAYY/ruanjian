REFACTOR_TASK = """请对以下代码给出**重构方案**：

目标：`{query}`
{goals}

要求：
1. 先用 `detect_code_smells` 与 `static_analyze` 取得客观坏味道清单。
2. 每个坏味道说明它**为什么**是问题（会导致什么具体风险，而不是「不够优雅」）。
3. 给出重构后的完整代码，并解释用了哪个设计模式/原则（SRP、DRY、KISS……）。
4. 说明重构的**风险**与如何验证（用 `run_tests` 或 `execute_code` 验证等价性）。

最终输出 Markdown 结构：`## 坏味道清单` / `## 重构方案` / `## 重构后代码` / `## 等价性验证` / `## 收益与风险`。
"""

FREEFORM_TASK = """{query}

请判断这个请求需要哪些信息，主动使用可用工具去获取，然后给出结论。
{goals}
"""

MODE_TEMPLATES: Dict[str, str] = {
    "review": REVIEW_TASK,
    "explain": EXPLAIN_TASK,
    "test": TEST_TASK,
    "refactor": REFACTOR_TASK,
    "ask": FREEFORM_TASK,
}

MODE_LABELS = {
    "review": "代码审查",
    "explain": "代码解释",
    "test": "测试生成",
    "refactor": "重构建议",
    "ask": "自由问答",
}


class PromptLibrary:
    """Prompt 模板库。"""

    def __init__(self, system_template: str = SYSTEM_PROMPT,
                 mode_templates: Optional[Dict[str, str]] = None):
        self.system_template = system_template
        self.mode_templates = dict(mode_templates or MODE_TEMPLATES)

    # ------------------------------------------------------------------ #
    def system_prompt(self, *, workspace: str, tools_catalog: str, extra: str = "") -> str:
        return self.system_template.format(
            severity=SEVERITY_SPEC,
            guard=FALSE_POSITIVE_GUARD,
            tools=tools_catalog,
            workspace=workspace,
            extra=extra,
        )

    def user_task_prompt(self, query: str, *, mode: str = "review", goals: str = "") -> str:
        template = self.mode_templates.get(mode) or FREEFORM_TASK
        goal_text = f"额外审查重点：{goals}" if goals.strip() else ""
        return template.format(query=query, goals=goal_text).strip()

    @staticmethod
    def mode_label(mode: str) -> str:
        return MODE_LABELS.get(mode, mode)

    @staticmethod
    def modes() -> Dict[str, str]:
        return dict(MODE_LABELS)
